#!/usr/bin/env python3
"""Conformance of jank's delay, promise and lazy seq with
JankSpecs/Concurrency/Once.lean, by outcome sets (see
JankSpecs/Conformance/OnceOutcomes.lean), and C5's deadlock.

    python3 conformance/concurrency/once.py [--runs N]

Each run: three futures each deref a delay (whose body counts its runs, then
returns or throws), deliver 0 or 1 to a promise and deref it, and realize a
lazy seq whose body throws on its first call. Separately, a delay whose body
derefs itself must hang (the model's stuck state), which a timeout detects.
"""

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPECS = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(HERE, "..", "lib"))
from jank_harness import run_jank, scratch_dir  # noqa: E402

PROGRAM = r'''(ns once-scenario (:require [clojure.string :as string]))

(defn run1 [throws?]
  (let [runs (atom 0)
        d (delay (swap! runs inc) (if throws? (throw (ex-info "boom" {})) :value))
        p (promise)
        calls (atom 0)
        ls (lazy-seq (when (= 1 (swap! calls inc)) (throw (ex-info "first" {}))) [1 2])
        fs (doall (for [i (range 3)]
                    (future
                      [(try @d "v" (catch :default _ "e"))
                       (do (deliver p (rand-int 2)) @p)
                       (try (first ls) :ok (catch :default _ :error))])))
        rs (doall (map deref fs))]
    (str "delay runs=" @runs " got=[" (string/join ", " (sort (map first rs))) "]"
         "|promise=[" (string/join ", " (distinct (map second rs))) "]"
         "|lazy calls=" @calls " errors=" (count (filter #{:error} (map #(nth % 2) rs))))))

(doseq [[o n] (frequencies (repeatedly RUNS #(run1 false)))] (println "RETURNS" o "#" n))
(doseq [[o n] (frequencies (repeatedly RUNS #(run1 true)))] (println "THROWS" o "#" n))
'''

SELF_DEREF = r'''(declare d)
(def d (delay (inc @d)))
(println "returned" (try @d (catch :default e "threw")))
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=2000)
    ns = ap.parse_args()
    work = scratch_dir("once-")
    path = os.path.join(work, "once_scenario.jank")
    with open(path, "w") as f:
        f.write(PROGRAM.replace("RUNS", str(ns.runs)))
    rc, out = run_jank(["run", path], work, timeout=1800)
    if rc != 0:
        print(out[-3000:])
        sys.exit(1)
    returns = re.findall(r"^RETURNS (.*) # (\d+)$", out, re.M)
    throws = re.findall(r"^THROWS (.*) # (\d+)$", out, re.M)
    for o, n in returns + throws:
        print(f"   {o}: {n} runs")

    selfpath = os.path.join(work, "self_deref.jank")
    with open(selfpath, "w") as f:
        f.write(SELF_DEREF)
    try:
        rc, out = run_jank(["run", selfpath], work, timeout=30)
        hung = False
        print(f"   self-dereffing delay: {out.strip()[-200:]!r}")
    except subprocess.TimeoutExpired:
        hung = True
        print("   self-dereffing delay: hangs (killed after 30s), as the model's stuck state")

    def quoted(xs):
        return "[" + ", ".join('"' + x + '"' for x in xs) + "]"
    gen = os.path.join(SPECS, "JankSpecs", "Conformance", "OnceObserved.lean")
    with open(gen, "w") as f:
        f.write("-- Generated by conformance/concurrency/once.py: outcomes of the real jank.\n"
                "import JankSpecs.Conformance.OnceOutcomes\n\nopen Once.Outcomes JankSpecs.Outcomes\n\n"
                f'#eval check "delay returns" (onceOutcomes .returns) {quoted([o for o, _ in returns])}\n'
                f'#eval check "delay throws" (onceOutcomes .throws) {quoted([o for o, _ in throws])}\n')
    p = subprocess.run(["lake", "build", "JankSpecs.Conformance.OnceObserved"], cwd=SPECS,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    lines = re.findall(r"(?:info|error): JankSpecs/Conformance/OnceObserved\.lean:\d+:\d+: (.*)", p.stdout)
    print("\n== against the model")
    for l in lines:
        print("   " + l)
    ok = p.returncode == 0 and len(lines) == 2 and all("conforms" in l for l in lines) and hung
    print("\nOK" if ok else "\nFAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
