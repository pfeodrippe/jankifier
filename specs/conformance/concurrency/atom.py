#!/usr/bin/env python3
"""Conformance of jank's atoms with JankSpecs/Concurrency/Atom.lean, by outcome
sets: each program runs many times in one jank process, and every outcome it
shows must be one `JankSpecs/Conformance/AtomOutcomes.lean` computes from the
model.

    python3 conformance/concurrency/atom.py [--runs N]

Programs:
- two futures doing two `swap! inc` each on an atom with a watch, which logs
  `[old new]`; the outcome is the final value and the log;
- one `swap! inc`, then `compare-and-set!` from the value it returned to that
  plus 10; the outcome is whether it succeeded. The model allows a spurious
  failure (`compare_exchange_weak`); the run also counts them under contention.
"""

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPECS = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(HERE, "..", "lib"))
from jank_harness import run_jank, scratch_dir  # noqa: E402

PROGRAM = r'''(ns atom-scenario (:require [clojure.string :as string]))

(defn swaps []
  (let [a (atom 0)
        log (atom [])]
    (add-watch a :w (fn [_ _ old new] (swap! log conj (str old ">" new))))
    (let [fs (doall (for [_ (range 2)] (future (dotimes [_ 2] (swap! a inc)))))]
      (doseq [f fs] @f))
    (str @a "|" (string/join "," @log))))

(defn cas []
  (let [a (atom 0)
        v (swap! a inc)]
    (str "cas=" (compare-and-set! a v (+ v 10)))))

;; compare-and-set! with the current value, while another thread keeps
;; swapping: a failure whose expected value was still there would be spurious,
;; but that can't be told apart from losing the race, so this only counts
;; failures where the value didn't change around the call.
(defn contended [n]
  (let [a (atom 0)
        stop (atom false)
        other (future (while (not @stop) (swap! a identity)))
        spurious (atom 0)]
    (dotimes [_ n]
      (let [v @a]
        (when-not (compare-and-set! a v v)
          (when (identical? v @a) (swap! spurious inc)))))
    (reset! stop true)
    @other
    @spurious))

(doseq [[o n] (frequencies (repeatedly RUNS swaps))] (println "SWAPS" o n))
(doseq [[o n] (frequencies (repeatedly RUNS cas))] (println "CAS" o n))
(println "CONTENDED-SPURIOUS" (contended 200000))
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=5000)
    ns = ap.parse_args()
    work = scratch_dir("atom-")
    path = os.path.join(work, "atom_scenario.jank")
    with open(path, "w") as f:
        f.write(PROGRAM.replace("RUNS", str(ns.runs)))
    rc, out = run_jank(["run", path], work, timeout=1200)
    if rc != 0:
        print(out[-3000:])
        sys.exit(1)
    swaps = re.findall(r"^SWAPS (\S+) (\d+)$", out, re.M)
    cas = re.findall(r"^CAS (\S+) (\d+)$", out, re.M)
    spurious = re.search(r"^CONTENDED-SPURIOUS (\d+)$", out, re.M).group(1)
    for o, n in swaps + cas:
        print(f"   {o}: {n} runs")
    print(f"   compare-and-set! failures with the value unchanged, under contention: {spurious} in 200000")

    gen = os.path.join(SPECS, "JankSpecs", "Conformance", "AtomObserved.lean")
    with open(gen, "w") as f:
        f.write("-- Generated by conformance/concurrency/atom.py: outcomes of the real jank.\n"
                "import JankSpecs.Conformance.AtomOutcomes\n\nopen Atom.Outcomes JankSpecs.Outcomes\n\n"
                f'#eval check "two futures, two swap! each" swapOutcomes {[o for o, _ in swaps]!r}\n'.replace("'", '"')
                + f'#eval check "swap! then compare-and-set!" casOutcomes {[o for o, _ in cas]!r}\n'.replace("'", '"'))
    p = subprocess.run(["lake", "build", "JankSpecs.Conformance.AtomObserved"], cwd=SPECS,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    lines = re.findall(r"(?:info|error): JankSpecs/Conformance/AtomObserved\.lean:\d+:\d+: (.*)", p.stdout)
    print("\n== against the model")
    for l in lines:
        print("   " + l)
    ok = p.returncode == 0 and all("conforms" in l for l in lines) and len(lines) == 2
    print("\nOK" if ok else "\nFAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
