# Generates native/unicode_table.inc: the Unicode classes the tokenizer's
# split pattern uses (letters by category, marks, numbers, white space), as
# sorted code point ranges. Run: python3 -I tools/gen_unicode.py > native/unicode_table.inc
import sys
import unicodedata

LU, LL, LT, LM, LO, M, N, WS = 1, 2, 4, 8, 16, 32, 64, 128
CATEGORY = {"Lu": LU, "Ll": LL, "Lt": LT, "Lm": LM, "Lo": LO,
            "Mn": M, "Mc": M, "Me": M, "Nd": N, "Nl": N, "No": N}
# Unicode's White_Space property, which \s matches.
WHITE = set(range(0x9, 0xE)) | {0x20, 0x85, 0xA0, 0x1680} | set(range(0x2000, 0x200B)) \
    | {0x2028, 0x2029, 0x202F, 0x205F, 0x3000}


def flags(cp):
    f = CATEGORY.get(unicodedata.category(chr(cp)), 0)
    if cp in WHITE:
        f |= WS
    return f


ranges = []
start, current = 0, flags(0)
for cp in range(1, 0x110000):
    f = flags(cp)
    if f != current:
        if current:
            ranges.append((start, cp - 1, current))
        start, current = cp, f
if current:
    ranges.append((start, 0x10FFFF, current))

out = sys.stdout
out.write("// Generated by tools/gen_unicode.py from Python's unicodedata %s. Do not edit.\n"
          % unicodedata.unidata_version)
out.write("// {first, last, flags}: 1 Lu, 2 Ll, 4 Lt, 8 Lm, 16 Lo, 32 M, 64 N, 128 white space.\n")
out.write("static constexpr unicode_range unicode_ranges[] = {\n")
for a, b, f in ranges:
    out.write("  { 0x%X, 0x%X, %d },\n" % (a, b, f))
out.write("};\n")
