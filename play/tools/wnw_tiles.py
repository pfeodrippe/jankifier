"""Witch n' Wiz's tiles, from its sources (game/meta_tiles.h: 6 bytes a tile, the flags last;
the flags and the door, key and mirror tiles in game/main.h): a character for each tile
index, for the model's view of a room.
Writes src/play/wnw_tiles.jank. Run from play/: python3 tools/wnw_tiles.py"""
import re

text = open('vendor/games/mbh-A53-witchnwiz/game/meta_tiles.h').read()
numbers = [int(n) for n in re.findall(r'\b\d+\b', text[text.index('{'):])]
flags = numbers[5::6]
SOLID, LADDER, WEB, PUSH, CARRY, MONSTER = 1, 2, 4, 8, 16, 128


def char(f):
    if f & MONSTER: return 'm'
    if f & PUSH: return 'B'
    if f & CARRY: return 'c'
    if f & WEB: return 'w'
    if f & LADDER: return 'H'
    if f & SOLID: return '#'
    return '.'


# Tiles by index (game/main.h): TILE_DOOR, TILE_KEY, TILE_DOOR_OPEN, TILE_MIRROR.
special = {70: 'D', 71: 'k', 72: 'E', 73: '|'}
chars = ''.join(special.get(i, char(f)) for i, f in enumerate(flags))
with open('src/play/wnw_tiles.jank', 'w') as out:
    out.write(';; SPDX-License-Identifier: MIT\n')
    out.write(";; Generated by tools/wnw_tiles.py from Witch n' Wiz's sources: a character for each tile\n")
    out.write(';; index: . empty, # solid, H ladder, w web, B a block to push, c something to carry,\n')
    out.write(';; m a monster, D a closed door, E the open door, k a key, | a mirror.\n')
    out.write('(ns play.wnw-tiles)\n\n')
    out.write('(def tile-chars "' + chars + '")\n')
print(len(flags), 'tiles:', chars)
