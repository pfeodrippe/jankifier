"""Nova the Squirrel's blocks and objects, from its sources (tools/metatiles.txt, in the order
of tools/metatileenum.s; tools/objectenum.s): for each block id, its name and a character
for the model's view of the level; each object type's name. Writes src/play/nova_blocks.jank.
Run from play/: python3 tools/nova_blocks.py"""
import re

SRC = 'vendor/games/NovaTheSquirrel/tools/'
names = [l.strip() for l in open(SRC + 'metatileenum.s') if l.startswith('  ') and l.strip() and not l.strip().startswith(';')]
flags = {}
current, seen = None, 0
for line in open(SRC + 'metatiles.txt'):
    if line.startswith('R '):
        current, seen = line.split()[1], 0
    elif line.startswith('C ') and current:
        seen += 1
        if seen == 3:
            flags[current] = line[2:].replace('.byt', '').strip()


def char(name, f):
    for word, c in [('COIN', 'o'), ('SPIKE', '^'), ('LADDER', 'H'), ('SPRING', 's'), ('DOOR', 'D'), ('SIGN', '?'),
                    ('PRIZE', '!'), ('WATER', '~'), ('LAVA', '~'), ('LOCK', 'L'), ('KEY', 'k'), ('HEART', '+'),
                    ('EXIT', 'E'), ('GOAL', 'E')]:
        if word in name:
            return c
    if 'M_SOLID_ALL' in f:
        return '#'
    # A ledge down drops her through (M_FALLABLE_LEDGE), and a platform it doesn't: both were
    # '=' and the agent pressed down on a solid ledge again and again.
    if 'M_SOLID_TOP' in f:
        return '=' if 'M_FALLABLE_LEDGE' in f else '-'
    return '.'


chars = ''.join(char(n, flags.get(n, '')) for n in names)
with open('src/play/nova_blocks.jank', 'w') as out:
    out.write(';; SPDX-License-Identifier: MIT\n')
    out.write(';; Generated by tools/nova_blocks.py from Nova the Squirrel\'s sources: its blocks, by id.\n')
    out.write('(ns play.nova-blocks)\n\n')
    out.write(';; A character for each block id: . empty, # solid, = a ledge (solid from above, down drops\n')
    out.write(';; through it), - a platform (solid from above, down doesn\'t drop through it), o coin,\n')
    out.write(';; ^ spikes, H ladder, s spring, D door, ? sign, ! prize block, ~ water or lava, L lock,\n')
    out.write(';; k key, + heart, E exit.\n')
    out.write('(def block-chars ' + '"' + chars + '"' + ')\n\n')
    out.write('(def names ' + '[' + ' '.join('"' + n + '"' for n in names) + '])\n')
objects = [l.strip() for l in open(SRC + 'objectenum.s') if l.startswith('  ') and l.strip() and not l.strip().startswith(';')]
with open('src/play/nova_blocks.jank', 'a') as out:
    out.write('\n;; Each object type\'s name, by type (an object slot\'s ObjectF1 >> 1).\n')
    out.write('(def objects ' + '[' + ' '.join('"' + n + '"' for n in objects) + '])\n')
print(len(objects), 'objects:', objects[:12])
print(len(names), 'blocks;', len(flags), 'with flags;', chars[:60])
